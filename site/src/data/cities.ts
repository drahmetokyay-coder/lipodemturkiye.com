/** Slug ile sehir bul */
export function getCityBySlug(slug: string): City | undefined {
  return cities.find((c) => c.slug === slug);
}

/** Bolgeye gore sehirleri filtrele */
export function getCitiesByRegion(region: Region): City[] {
  return cities.filter((c) => c.region === region);
}

/** Klinigi olan sehirleri getir */
export function getCitiesWithClinics(): City[] {
  return cities.filter((c) => c.hasClinics);
}

/** Tum sluglari getir (generateStaticParams icin) */
export function getAllCitySlugs(): string[] {
  return cities.map((c) => c.slug);
}
